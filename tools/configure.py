#!/usr/bin/env python3
"""Generate a single explicit crypto profile. Never guesses from Android version."""
import argparse
import datetime
import json
import pathlib
import re
from partition_layout import extra_mounts, recovery_flags

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEVICE = ROOT


def date(value):
    datetime.date.fromisoformat(value)
    return value


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--keymaster', type=int, choices=(3, 4), required=True)
    p.add_argument('--policy', type=int, choices=(1, 2), required=True)
    p.add_argument('--fileencryption', required=True,
                   help='Exact fileencryption value from the installed vendor fstab')
    p.add_argument('--wrapped-key', action='store_true', help='Only if ROM fstab has the separate wrappedkey flag')
    p.add_argument('--os-version', required=True)
    p.add_argument('--security-patch', type=date, required=True)
    p.add_argument('--vendor-patch', type=date, required=True)
    p.add_argument('--metadata-partition', choices=('none', 'logdump', 'metadata', 'cust'), required=True)
    p.add_argument('--metadata-encryption', help='Exact metadata_encryption value, if present in ROM fstab')
    p.add_argument('--dm-options-version', type=int, choices=(1, 2), help='Installed ROM dm-default-key options format version')
    p.add_argument('--keydirectory', help='Exact keydirectory from ROM fstab; must be below /metadata/')
    a = p.parse_args()
    if not re.fullmatch(r'[0-9]+(?:\.[0-9]+){0,2}', a.os_version):
        p.error('invalid OS version')
    if not re.fullmatch(r'[a-zA-Z0-9_:+.-]+', a.fileencryption):
        p.error('invalid fileencryption token')
    tokens = a.fileencryption.split(':')
    if ('v2' in tokens and a.policy != 2) or ('v1' in tokens and a.policy != 1):
        p.error('fileencryption and --policy disagree')
    if a.fileencryption == 'ice' and a.policy != 1:
        p.error('this legacy ice profile requires policy 1; supply the real v2 cipher options for policy 2')
    if a.fileencryption == 'ice':
        p.error('The Android 16 libfscrypt parser requires explicit ciphers; establish actual policy/cipher options before using an old ice fstab')
    if bool(a.metadata_encryption) != bool(a.keydirectory):
        p.error('--metadata-encryption and --keydirectory must be supplied together')
    if bool(a.metadata_encryption) != bool(a.dm_options_version):
        p.error('metadata encryption also requires its actual --dm-options-version')
    if a.metadata_encryption:
        if a.metadata_partition == 'none':
            p.error('metadata encryption requires an explicit metadata partition')
        if not re.fullmatch(r'[a-zA-Z0-9_:+.-]+', a.metadata_encryption):
            p.error('invalid metadata_encryption token')
        if not re.fullmatch(r'/metadata/[a-zA-Z0-9_/-]+', a.keydirectory) or '..' in a.keydirectory:
            p.error('invalid keydirectory')
    (DEVICE / 'crypto-profile.mk').write_text(
        '# Generated by tools/configure.py; matches the installed ROM, not its marketing version.\n'
        f'TW_USE_FSCRYPT_POLICY := {a.policy}\n'
        'TW_INCLUDE_CRYPTO := true\nTW_INCLUDE_CRYPTO_FBE := true\n'
        f'TW_INCLUDE_FBE_METADATA_DECRYPT := {str(bool(a.metadata_encryption)).lower()}\n'
        f'BOARD_USES_METADATA_PARTITION := {str(a.metadata_partition != "none").lower()}\n')
    (DEVICE / 'crypto-profile.json').write_text(json.dumps(vars(a), indent=2) + '\n')
    root = DEVICE / 'recovery/root'
    (root / 'system/etc').mkdir(parents=True, exist_ok=True)
    (root / 'vendor/etc/vintf').mkdir(parents=True, exist_ok=True)
    (root / 'system/etc/dipper-crypto.prop').write_text(
        f'ro.build.version.release={a.os_version}\n'
        f'ro.build.version.security_patch={a.security_patch}\n'
        f'ro.vendor.build.security_patch={a.vendor_patch}\n'
        f'ro.crypto.volume.options={a.fileencryption}\n'
        + (f'ro.crypto.dm_default_key.options_format.version={a.dm_options_version}\n'
           if a.dm_options_version else ''))
    (root / 'vendor/etc/vintf/manifest.xml').write_text(f'''<manifest version="1.0" type="device">
    <hal format="hidl"><name>android.hardware.keymaster</name><transport>hwbinder</transport>
        <version>{a.keymaster}.0</version><interface><name>IKeymasterDevice</name><instance>default</instance></interface></hal>
    <hal format="hidl"><name>android.hardware.gatekeeper</name><transport>hwbinder</transport>
        <version>1.0</version><interface><name>IGatekeeper</name><instance>default</instance></interface></hal>
</manifest>
''')
    ld = '    setenv LD_LIBRARY_PATH /vendor/lib64:/vendor/lib64/hw:/system/lib64\n'
    common = '    user root\n    group root system drmrpc\n' + ld + '    disabled\n    seclabel u:r:recovery:s0\n'
    rc = '''# Generated: exactly one Keymaster service; no version-name guessing.
on fs
    exec u:r:recovery:s0 -- /system/bin/sh /system/bin/dipper-crypto-prepare.sh

on property:dipper.crypto.ready=1
    start dipper-qseecomd

on property:vendor.sys.listeners.registered=true && property:dipper.crypto.ready=1
    start dipper-keymaster
    start dipper-gatekeeper

on property:sys.listeners.registered=true && property:dipper.crypto.ready=1
    start dipper-keymaster
    start dipper-gatekeeper

'''
    for name, binary in [('qseecomd', 'qseecomd'),
                         ('keymaster', f'android.hardware.keymaster@{a.keymaster}.0-service-qti'),
                         ('gatekeeper', 'android.hardware.gatekeeper@1.0-service-qti')]:
        rc += f'service dipper-{name} /system/bin/{binary}\n{common}\n'
    (root / 'init.recovery.dipper-crypto.rc').write_text(rc)
    # Static partitions only. Do not import stock formattable/wipe flags.
    lines = ['# block_device mount_point fs_type mount_flags fs_mgr_flags']
    for part, mount in [('system', '/system'), ('vendor', '/vendor')]:
        for fs, opt in [('ext4', 'ro'), ('erofs', 'ro')]:
            lines.append(f'/dev/block/bootdevice/by-name/{part} {mount} {fs} {opt} wait,recoveryonly')
    if a.metadata_partition != 'none':
        lines.append(f'/dev/block/bootdevice/by-name/{a.metadata_partition} /metadata ext4 noatime,nosuid,nodev wait')
    flags = f'wait,fileencryption={a.fileencryption},quota'
    if a.wrapped_key:
        flags += ',wrappedkey'
    if a.metadata_encryption:
        flags += f',metadata_encryption={a.metadata_encryption},keydirectory={a.keydirectory}'
    for fs in ('f2fs', 'ext4'):
        lines.append(f'/dev/block/bootdevice/by-name/userdata /data {fs} noatime,nosuid,nodev {flags}')
    lines += extra_mounts(a.metadata_partition)
    lines += ['/dev/block/bootdevice/by-name/misc /misc emmc defaults defaults']
    (DEVICE / 'recovery/recovery.fstab').write_text('\n'.join(lines) + '\n')
    # vold uses ReadDefaultFstab, independently of the TWRP fstab parser.
    # Provide a default qcom fstab as well, containing the same data/metadata options.
    default_lines = [line for line in lines if ' /data ' in line or ' /metadata ' in line]
    (root / 'fstab.qcom').write_text('\n'.join(default_lines) + '\n')
    (root / 'vendor/etc/fstab.qcom').write_text('\n'.join(default_lines) + '\n')
    twflags = recovery_flags(a.metadata_partition, decrypt=True, data=True)
    (root / 'system/etc/twrp.flags').write_text(twflags)
    print('Generated:', DEVICE / 'crypto-profile.json')


if __name__ == '__main__':
    main()
